import static com.pedropathing.ivy.pedro.PedroCommands.follow;

@Autonomous
public class blueAutoShootClose extends OpMode {
    private Follower follower;
    private shooter shooter;
    private final PoseFactory p = PoseFactory.degrees();

    private final PoseFactory poseFactory = PoseFactory.degrees();

    private final Pose start = poseFactory.of(83.2955, 8.7346, 270);
    private final Pose path1 = poseFactory.of(82.8588, 24.2083, 180);
    private final Pose point2 = poseFactory.of(129.1344, 20.7788, 175.7615);

    public Path path1() {
        return Paths.line(start, path1).linear(start, path1);
    }

    public Path path2() {
        return Paths.line(path1, point2).reverseTangent();
    }
    private Command autoRoutine() {
        return sequential(
                //instant(() -> shooter.shooterSetVelocity(965)),
                waitMs(3000),
                //instant(() -> shooter.shooterSetVelocity(0)),

                follow(follower, path1()),
                follow(follower, path2()));


    }

    @Override
    public void init() {
        Scheduler.reset();
        follower = Constants.create(hardwareMap);
        follower.setPose(start);//sets the starting point of your Robot
        follower.update();
        shooter = new shooter(hardwareMap);
    }
    @Override
    public void start() {
        schedule(autoRoutine());
    }

    @Override
    public void loop() {
        follower.update();
        Scheduler.execute();
    }

    @Override
    public void stop() {
        OpModeStorage.autonomousEndPose = follower.pose(); //saves your position in that file
    }



}
